#!/usr/bin/env python3
"""Builds DashboardPage.h from web/dashboard.html and web/es.json.

The Spanish texts (web/es.json, English -> Spanish) are inserted into the page
at the /*ES-DICTIONARY*/ marker. The page is stored gzip-compressed (about 21 KB instead of 77 KB), so the
controller sends it in roughly a quarter of the time. Edit web/dashboard.html,
then run from the sketch folder:

    python3 tools/build_dashboard.py

and upload the firmware again. The output is deterministic (no timestamp), so
an unchanged page gives an unchanged header.
"""
import gzip, os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'web', 'dashboard.html')
dst = os.path.join(here, '..', 'DashboardPage.h')

import json
page = open(src, encoding='utf-8').read()
es = json.load(open(os.path.join(here, '..', 'web', 'es.json'), encoding='utf-8'))
marker = '/*ES-DICTIONARY*/{}'
if marker not in page:
    sys.exit('web/dashboard.html has no /*ES-DICTIONARY*/{} marker')
page = page.replace(marker, json.dumps(es, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/'))
html = page.encode('utf-8')
gz = gzip.compress(html, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(gz), 20):
    lines.append('  ' + ','.join('0x%02x' % b for b in gz[i:i + 20]) + ',')

out = f"""#ifndef DASHBOARD_PAGE_H
#define DASHBOARD_PAGE_H

// GENERATED by tools/build_dashboard.py from web/dashboard.html. Do not edit by hand:
// edit web/dashboard.html and run the script again.
//
// Single-page dashboard served at "/" with Content-Encoding: gzip. It polls
// /api/status every 2 s and talks to the controller only through the /api/*
// endpoints in GreyWaterNet.cpp. No external fonts or scripts, so it works on
// a home network without internet.
//
// Page: {len(html)} bytes, compressed: {len(gz)} bytes.

#include <Arduino.h>

static const size_t DASHBOARD_HTML_GZ_LEN = {len(gz)};
static const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {{
{chr(10).join(lines)}
}};

#endif
"""
open(dst, 'w').write(out)
print(f'DashboardPage.h: {len(html)} bytes -> {len(gz)} bytes gzip')
